//! Verification of the HS256 token issued by pgsql.php (`action: event_token`).
//!
//! The token says who the client is and which topics/scopes it may see.
//! Those claims come from `notify.claims()`, executed by PostgreSQL under the
//! user's role, so the daemon itself never decides about permissions.

use std::collections::HashMap;
use std::time::{SystemTime, UNIX_EPOCH};

use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine as _};
use hmac::{Hmac, Mac};
use serde::Deserialize;
use sha2::Sha256;

use crate::feed::Access;

type HmacSha256 = Hmac<Sha256>;

/// Topic map as it appears in JSON: topic -> null | [scope, ...]. Scopes may be strings or numbers.
pub type TopicMap = HashMap<String, Option<Vec<serde_json::Value>>>;

#[derive(Deserialize)]
struct RawClaims {
    aud: String,
    sub: String,
    #[serde(default)]
    role: Option<String>,
    #[serde(default)]
    topics: TopicMap,
    exp: i64,
}

#[derive(Debug)]
pub struct Claims {
    pub sub: String,
    pub role: Option<String>,
    pub exp: i64,
    pub access: Access,
}

pub fn now() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

pub fn access_from(map: TopicMap) -> Access {
    let topics = map
        .into_iter()
        .map(|(topic, scopes)| {
            let scopes = scopes.map(|list| {
                list.into_iter()
                    .map(|v| match v {
                        serde_json::Value::String(s) => s,
                        other => other.to_string(),
                    })
                    .collect()
            });
            (topic, scopes)
        })
        .collect();
    Access { topics }
}

fn b64(part: &str) -> Result<Vec<u8>, &'static str> {
    URL_SAFE_NO_PAD.decode(part).map_err(|_| "malformed token")
}

pub fn verify(token: &str, secret: &[u8], aud: &str, now: i64) -> Result<Claims, &'static str> {
    let mut parts = token.split('.');
    let (h, p, s) = match (parts.next(), parts.next(), parts.next(), parts.next()) {
        (Some(h), Some(p), Some(s), None) => (h, p, s),
        _ => return Err("malformed token"),
    };

    let header: serde_json::Value =
        serde_json::from_slice(&b64(h)?).map_err(|_| "malformed token")?;
    if header.get("alg").and_then(|v| v.as_str()) != Some("HS256") {
        return Err("unsupported token algorithm");
    }

    let mut mac = HmacSha256::new_from_slice(secret).map_err(|_| "invalid secret")?;
    mac.update(h.as_bytes());
    mac.update(b".");
    mac.update(p.as_bytes());
    mac.verify_slice(&b64(s)?)
        .map_err(|_| "invalid token signature")?;

    let raw: RawClaims = serde_json::from_slice(&b64(p)?).map_err(|_| "malformed token claims")?;
    if raw.exp <= now {
        return Err("token expired");
    }
    if raw.aud != aud {
        return Err("token audience mismatch");
    }

    Ok(Claims {
        sub: raw.sub,
        role: raw.role,
        exp: raw.exp,
        access: access_from(raw.topics),
    })
}

/// HMAC-SHA256 as lowercase hex (used to sign webhook bodies).
pub fn sign_hex(secret: &str, body: &[u8]) -> String {
    let mut mac =
        HmacSha256::new_from_slice(secret.as_bytes()).expect("HMAC accepts any key length");
    mac.update(body);
    mac.finalize()
        .into_bytes()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::feed::Event;

    // Generated by pgsql.php's event_token code with secret "test-secret",
    // aud "dev_local", exp 4102444800 (year 2100). Guards PHP <-> Rust compatibility.
    const PHP_TOKEN: &str = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJhdWQiOiJkZXZfbG9jYWwiLCJzdWIiOiJhcHBfdXNlciIsInJvbGUiOiJhcHBfdXNlciIsInRvcGljcyI6eyJjcm0uY3VzdG9tZXIiOm51bGwsImRlY2suY2FyZCI6WyI3Iiw4XX0sImlhdCI6MTcwMDAwMDAwMCwiZXhwIjo0MTAyNDQ0ODAwfQ.GpK1e-yZtIy6LL0-M7Y5xubfZG0jmKOKxbFchALrTfc";

    fn ev(topic: &str, scope: Option<&str>) -> Event {
        Event {
            xid: 1,
            topic: topic.into(),
            scope: scope.map(Into::into),
            json: String::new(),
        }
    }

    #[test]
    fn accepts_token_from_php() {
        let c = verify(PHP_TOKEN, b"test-secret", "dev_local", 1_700_000_000).expect("valid");
        assert_eq!(c.sub, "app_user");
        assert!(c.access.allows(&ev("crm.customer", Some("1"))));
        assert!(c.access.allows(&ev("deck.card", Some("7"))));
        assert!(c.access.allows(&ev("deck.card", Some("8")))); // numeric scope in JSON
        assert!(!c.access.allows(&ev("deck.card", Some("9"))));
        assert!(!c.access.allows(&ev("other", None)));
    }

    #[test]
    fn rejects_bad_tokens() {
        assert_eq!(
            verify(PHP_TOKEN, b"wrong", "dev_local", 0).unwrap_err(),
            "invalid token signature"
        );
        assert_eq!(
            verify(PHP_TOKEN, b"test-secret", "other", 0).unwrap_err(),
            "token audience mismatch"
        );
        assert_eq!(
            verify(PHP_TOKEN, b"test-secret", "dev_local", 4_102_444_800).unwrap_err(),
            "token expired"
        );
        assert_eq!(verify("a.b", b"x", "a", 0).unwrap_err(), "malformed token");
        let mut tampered = PHP_TOKEN.to_string();
        tampered.insert(PHP_TOKEN.find('.').unwrap() + 3, 'A');
        assert!(verify(&tampered, b"test-secret", "dev_local", 0).is_err());
    }

    #[test]
    fn webhook_signature_is_hex_hmac() {
        // echo -n 'body' | openssl dgst -sha256 -hmac 'k'
        assert_eq!(
            sign_hex("k", b"body"),
            "c6d811ef3aeb02437cd423f1abe13209041864630bdc4e2c04def5c7b0031a23"
        );
    }
}
